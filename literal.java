package com.lcy.literal;

public class literal {
    static void main(String[] args) {
        //输出一下信息；8岁，27kg,霸王龙
        System.out.println("8岁，27kg,霸王龙");
        //输出恐龙的名字：霸王龙
        System.out.println("霸王龙");
        //输出恐龙的性别：雄性
        System.out.println("雄性");
        //输出岁数：8
        System.out.println(8);
        //输出体重：27kg
        System.out.println("27kg");

    }
}
